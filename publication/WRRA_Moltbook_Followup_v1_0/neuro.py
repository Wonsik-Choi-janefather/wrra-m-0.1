"""Budget-gated finite extension of the book's actual chapter 42 model.

All coefficients and the failure sequence are hypothetical. Dynamic programming
enumerates the state probabilities; no human data or FEP implementation is used.
"""
import math


def probability(residue,resource, residue_coefficient=1.1):
    return 1/(1+math.exp(-(1.2+.9*resource-residue_coefficient*residue)))


def distribution(budget,failures,residue_coefficient=1.1):
    if type(budget) is not int or budget<1:raise ValueError('positive integer budget required')
    state={budget:1.0};residue=0.0
    trace=[]
    for failed in failures:
        if type(failed) is not int or failed not in (0,1):raise ValueError('binary exogenous feedback required')
        successor={}
        for remaining,mass in state.items():
            p=probability(residue,remaining/budget,residue_coefficient) if remaining>=1 else 0.0
            successor[remaining]=successor.get(remaining,0)+mass*(1-p)
            if p:successor[remaining-1]=successor.get(remaining-1,0)+mass*p
        assert abs(sum(successor.values())-1)<2e-14 and min(successor)>=0
        trace.append(dict(residue_before=residue,states={str(k):v for k,v in successor.items()}))
        state=successor
        residue=.8*residue+.4*failed
    mean=sum((budget-b)*p for b,p in state.items())
    variance=sum((budget-b-mean)**2*p for b,p in state.items())
    return dict(budget=budget,mean_actions=mean,variance_actions=variance,
      probability_budget_exhausted=state.get(0,0),final_distribution={str(k):v for k,v in state.items()},trace=trace)


def run():
    residue=0
    for _ in range(5):residue=.8*residue+.4
    old=[dict(resource=b,probability=probability(residue,b),bernoulli_variance=probability(residue,b)*(1-probability(residue,b))) for b in (1.0,.3)]
    failures=[1]*5+[0]*15
    full=[distribution(b,failures) for b in (3,6,12)]
    ablation=[distribution(b,failures,0) for b in (3,6,12)]
    return dict(original_five_failure_residue=residue,original_model=old,feedback=failures,
      full=full,residue_ablated=ablation,
      assumptions=['one abstract token per accepted action; zero monitoring cost in this domain profile',
      'all actions otherwise available; exogenous feedback is supplied even when no action occurs',
      'resource normalized by initial budget; no replenishment; initial residue zero',
      'ablation is a structural diagnostic, not a tuned competing theory'],
      scope='Implemented finite hypothetical choice model. Feedback is not generated by action. No target-tracking, human fit, consciousness measure, FEP integration or comparative superiority claim.')
